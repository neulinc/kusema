import React, { useEffect, useState } from "react";
import { useTranslation } from "react-i18next";
import { openUrl } from "@tauri-apps/plugin-opener";
import { Button } from "../../ui/Button";
import { SettingContainer } from "../../ui/SettingContainer";
import { SettingsGroup } from "../../ui/SettingsGroup";
import { TextLink } from "../../ui/TextLink";

const HANDY_URL = "https://github.com/cjpais/Handy";

interface Component {
  name: string;
  version: string;
  license: string;
  url: string;
}

interface Model {
  name: string;
  license: string;
  url: string;
  notice?: string;
}

/** Generated by scripts/generate-credits.ts. */
interface Credits {
  nvidiaNotice: string;
  nvidiaLicenseUrl: string;
  models: Model[];
  rust: Component[];
  js: Component[];
  others: Component[];
}

const Fold: React.FC<{
  title: string;
  onOpen?: () => void;
  children: React.ReactNode;
}> = ({ title, onOpen, children }) => (
  <details
    className="border-t border-line px-4 py-3"
    onToggle={(ev) => ev.currentTarget.open && onOpen?.()}
  >
    <summary className="cursor-pointer rounded text-sm font-medium focus:outline-none focus-visible:ring-2 focus-visible:ring-logo-primary">
      {title}
    </summary>
    <div className="mt-3 max-h-[420px] overflow-auto">{children}</div>
  </details>
);

const ComponentList: React.FC<{ items: Component[] }> = ({ items }) => (
  <ul className="m-0 list-none p-0 text-sm select-text">
    {items.map((item) => (
      <li
        key={`${item.name}@${item.version}`}
        className="flex flex-wrap justify-between gap-x-4 py-[2px]"
      >
        <span className="min-w-0 break-words">
          {item.name} {item.version}
        </span>
        <span className="text-ink-2">{item.license}</span>
      </li>
    ))}
  </ul>
);

/** Who Kusema is built on, and the licenses that come with that. */
export const CreditsSettings: React.FC = () => {
  const { t } = useTranslation();
  const [credits, setCredits] = useState<Credits | null>(null);
  const [notices, setNotices] = useState<string | null>(null);

  // Their own chunks: most people never open these.
  useEffect(() => {
    import("@/content/credits.json")
      .then((module) => setCredits(module.default as Credits))
      .catch(console.error);
  }, []);
  const loadNotices = () => {
    if (notices !== null) return;
    import("@/content/third-party-notices.txt?raw")
      .then((module) => setNotices(module.default))
      .catch(console.error);
  };

  const components = credits
    ? [...credits.rust, ...credits.js, ...credits.others].sort((a, b) =>
        a.name.localeCompare(b.name),
      )
    : [];

  return (
    <SettingsGroup title={t("settings.about.credits.title")}>
      <SettingContainer
        title={t("settings.about.credits.handy.title")}
        description={t("settings.about.credits.handy.description")}
        descriptionMode="inline"
        grouped
      >
        <Button
          variant="secondary"
          size="md"
          onClick={() => openUrl(HANDY_URL).catch(console.error)}
        >
          {t("settings.about.credits.handy.button")}
        </Button>
      </SettingContainer>
      {credits && (
        <>
          <div className="border-t border-line px-4 py-3 text-sm">
            <p className="m-0 select-text">{credits.nvidiaNotice}</p>
            <TextLink
              onClick={() =>
                openUrl(credits.nvidiaLicenseUrl).catch(console.error)
              }
            >
              {t("settings.about.credits.nvidiaLicense")}
            </TextLink>
          </div>
          <Fold
            title={t("settings.about.credits.models", {
              count: credits.models.length,
            })}
          >
            <ul className="m-0 list-none p-0 text-sm select-text">
              {credits.models.map((model) => (
                <li
                  key={model.url}
                  className="flex flex-wrap justify-between gap-x-4 py-[2px]"
                >
                  <TextLink
                    onClick={() => openUrl(model.url).catch(console.error)}
                  >
                    {model.name}
                  </TextLink>
                  <span className="text-ink-2">{model.license}</span>
                </li>
              ))}
            </ul>
          </Fold>
          <Fold
            title={t("settings.about.credits.components", {
              count: components.length,
            })}
          >
            <ComponentList items={components} />
          </Fold>
        </>
      )}
      <Fold title={t("settings.about.credits.notices")} onOpen={loadNotices}>
        <pre className="m-0 font-mono text-xs break-words whitespace-pre-wrap select-text">
          {notices ?? t("settings.about.credits.loading")}
        </pre>
      </Fold>
      <div className="border-t border-line px-4 py-3">
        <p className="m-0 text-sm font-medium">
          {t("settings.about.acknowledgments.ggml.title")}
        </p>
        <p className="m-0 text-sm text-ink-3">
          {t("settings.about.acknowledgments.ggml.details")}
        </p>
      </div>
    </SettingsGroup>
  );
};
